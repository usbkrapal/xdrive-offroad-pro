"""Link stubs and ELF checks for xop-camrx, without third-party modules (a dependency-free counterpart of the
stub-source / set-interp / check-imports steps of idrive-apps' cluster-render tools/ramses_abi.py).

    elfabi.py stub-source LIST.symbols > stub.c          link-only stub ("name TYPE size" lines)
    elfabi.py set-interp BINARY /lib/ld-linux-x86-64.so.2
    elfabi.py check BINARY --interp PATH --glibc 2.27 --needed lib1,lib2,... LIST.symbols...

check fails when: the interpreter differs; a NEEDED library is not in --needed; a GLIBC_x.y version needed is newer
than --glibc; an undefined dynamic symbol is neither versioned glibc nor exported by one of the LIST files.
"""
import struct
import sys


def load_symbols(path):
    out = {}
    with open(path) as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith('#'):
                continue
            parts = line.split()
            if len(parts) >= 3:
                out[parts[0]] = (parts[1], int(parts[2]))
    return out


def stub_source(path):
    print('/* Link-only stub for the library %s lists. Generated by native/camrx/tools/elfabi.py. */' % path)
    for name, (kind, size) in sorted(load_symbols(path).items()):
        if kind == 'FUNC':
            print('void %s(void) {}' % name)
        else:
            print('const unsigned char %s[%d] = {0};' % (name, max(size, 1)))


class Elf:
    def __init__(self, data):
        if data[:4] != b'\x7fELF' or data[4] != 2 or data[5] != 1:
            raise ValueError('not a little-endian ELF64')
        self.d = data
        (self.e_type, self.e_machine, _, _, self.phoff, self.shoff, _, _, self.phentsize, self.phnum, self.shentsize,
         self.shnum, self.shstrndx) = struct.unpack_from('<HHIQQQIHHHHHH', data, 16)
        self.ph = [struct.unpack_from('<IIQQQQQQ', data, self.phoff + i * self.phentsize) for i in range(self.phnum)]
        self.sh = [struct.unpack_from('<IIQQQQIIQQ', data, self.shoff + i * self.shentsize) for i in range(self.shnum)]

    def section(self, kind):
        return [s for s in self.sh if s[1] == kind]

    def cstr(self, off):
        end = self.d.index(b'\0', off)
        return self.d[off:end].decode('latin-1')

    def interp(self):
        for p in self.ph:
            if p[0] == 3:   # PT_INTERP
                return self.d[p[2]:p[2] + p[5]].rstrip(b'\0').decode(), p[2], p[5]
        return None, 0, 0

    def dynamic(self):
        dyn = self.section(6)   # SHT_DYNAMIC
        if not dyn:
            return [], None
        s = dyn[0]
        strtab = self.sh[s[6]]   # sh_link -> .dynstr
        needed = []
        for i in range(s[5] // 16):
            tag, val = struct.unpack_from('<qQ', self.d, s[4] + i * 16)
            if tag == 0:
                break
            if tag == 1:   # DT_NEEDED
                needed.append(self.cstr(strtab[4] + val))
        return needed, strtab

    def undefined(self):
        ds = self.section(11)   # SHT_DYNSYM
        if not ds:
            return []
        s = ds[0]
        strtab = self.sh[s[6]]
        versym = self.section(0x6fffffff)
        verneed = self.section(0x6ffffffe)
        names = {}
        if verneed:
            v = verneed[0]
            vstr = self.sh[v[6]]
            off = v[4]
            for _ in range(v[7]):   # sh_info: entries
                _ver, cnt, _file, aux, nxt = struct.unpack_from('<HHIII', self.d, off)
                a = off + aux
                for _ in range(cnt):
                    _h, _f, other, name, anext = struct.unpack_from('<IHHII', self.d, a)
                    names[other] = self.cstr(vstr[4] + name)
                    if not anext:
                        break
                    a += anext
                if not nxt:
                    break
                off += nxt
        out = []
        n = s[5] // 24
        for i in range(1, n):
            name, info, _other, shndx, _value, _size = struct.unpack_from('<IBBHQQ', self.d, s[4] + i * 24)
            if shndx != 0:
                continue
            nm = self.cstr(strtab[4] + name)
            if not nm:
                continue
            ver = None
            if versym:
                vi = struct.unpack_from('<H', self.d, versym[0][4] + i * 2)[0] & 0x7fff
                ver = names.get(vi)
            bind = info >> 4
            out.append((nm, ver, bind))
        return out

    def dyn_tags(self):
        dyn = self.section(6)
        out = []
        if not dyn:
            return out
        s = dyn[0]
        for i in range(s[5] // 16):
            tag, val = struct.unpack_from('<qQ', self.d, s[4] + i * 16)
            if tag == 0:
                break
            out.append((tag, val))
        return out

    def defined_dynamic(self):
        ds = self.section(11)
        if not ds:
            return []
        s = ds[0]
        strtab = self.sh[s[6]]
        out = []
        for i in range(1, s[5] // 24):
            name, info, _other, shndx, _value, _size = struct.unpack_from('<IBBHQQ', self.d, s[4] + i * 24)
            if shndx == 0:
                continue
            nm = self.cstr(strtab[4] + name)
            if nm:
                out.append((nm, info >> 4))
        return out

    def versions_needed(self):
        out = []
        for v in self.section(0x6ffffffe):
            vstr = self.sh[v[6]]
            off = v[4]
            for _ in range(v[7]):
                _ver, cnt, file_, aux, nxt = struct.unpack_from('<HHIII', self.d, off)
                lib = self.cstr(vstr[4] + file_)
                a = off + aux
                for _ in range(cnt):
                    _h, _f, _o, name, anext = struct.unpack_from('<IHHII', self.d, a)
                    out.append((lib, self.cstr(vstr[4] + name)))
                    if not anext:
                        break
                    a += anext
                if not nxt:
                    break
                off += nxt
        return out


def set_interp(path, interp):
    data = bytearray(open(path, 'rb').read())
    e = Elf(bytes(data))
    cur, off, size = e.interp()
    if cur is None:
        print('FAIL  %s has no PT_INTERP' % path)
        return 1
    new = interp.encode() + b'\0'
    if len(new) > size:
        print('FAIL  %s does not fit in PT_INTERP (%d bytes)' % (interp, size))
        return 1
    data[off:off + size] = new.ljust(size, b'\0')
    open(path, 'wb').write(data)
    print('OK    %s: interpreter %s (was %s)' % (path, interp, cur))
    return 0


def ver_tuple(v):
    return tuple(int(x) for x in v.split('_', 1)[1].split('.'))


def check(argv):
    binary = argv[0]
    interp = glibc = None
    needed_ok = []
    lists = []
    stripped = False
    ldso_ok = []
    i = 1
    while i < len(argv):
        if argv[i] == '--interp':
            interp = argv[i + 1]; i += 2
        elif argv[i] == '--glibc':
            glibc = argv[i + 1]; i += 2
        elif argv[i] == '--ldso-versions':
            ldso_ok = argv[i + 1].split(','); i += 2
        elif argv[i] == '--stripped':
            stripped = True; i += 1
        elif argv[i] == '--needed':
            needed_ok = argv[i + 1].split(','); i += 2
        else:
            lists.append(argv[i]); i += 1
    e = Elf(open(binary, 'rb').read())
    problems = []
    if e.e_machine != 62:
        problems.append('machine %d is not x86-64' % e.e_machine)
    cur, _, _ = e.interp()
    if interp and cur != interp:
        problems.append('interpreter %s, expected %s' % (cur, interp))
    needed, _ = e.dynamic()
    for n in needed:
        if n not in needed_ok:
            problems.append('NEEDED %s is not one of %s' % (n, ','.join(needed_ok)))
    vers = e.versions_needed()
    newest = None
    for lib, v in vers:
        if v.startswith('GLIBC_') and v[6:7].isdigit():
            if newest is None or ver_tuple(v) > ver_tuple(newest):
                newest = v
            if glibc and ver_tuple(v) > tuple(int(x) for x in glibc.split('.')):
                problems.append('%s needs %s (unit: %s)' % (lib, v, glibc))
    for lib, v in vers:
        if lib.startswith('ld-linux') and v not in ldso_ok:
            problems.append('needs %s from the dynamic loader (allowed: %s)' % (v, ','.join(ldso_ok) or 'none'))
    # no libstdc++ / libgcc_s C++ runtime versions (Zig links LLVM libc++ statically)
    for lib, v in vers:
        if v.startswith('GLIBCXX_') or v.startswith('CXXABI_'):
            problems.append('%s needs %s (no libstdc++ dependency allowed)' % (lib, v))
    tags = e.dyn_tags()
    for tag, val in tags:
        if tag in (15, 29):
            problems.append('DT_RPATH/DT_RUNPATH present')
        if tag == 22 or (tag == 30 and val & 4):
            problems.append('text relocations (TEXTREL)')
    stack = [p for p in e.ph if p[0] == 0x6474e551]
    if not stack:
        problems.append('no PT_GNU_STACK (executable stack by default)')
    elif stack[0][1] & 1:
        problems.append('executable stack (PT_GNU_STACK has X)')
    # the static C++ runtime must not be exported: the unit's libstdc++ users (MSDK, IAS bridge) would bind to it
    for nm, bind in e.defined_dynamic():
        if bind in (1, 2) and (nm.startswith('_Z') or nm.startswith('__cxa_') or nm.startswith('__gxx_') or nm.startswith('_Unwind_')):
            problems.append('exports C++ runtime symbol %s' % nm)
    if b'/Users/' in e.d or b'/private/tmp/' in e.d:
        problems.append('build-machine paths embedded (/Users/ or /private/tmp/)')
    if stripped and e.section(2):
        problems.append('not stripped (.symtab present)')
    exported = {}
    for l in lists:
        exported.update(load_symbols(l))
    unit = 0
    for nm, ver, bind in e.undefined():
        if ver and (ver.startswith('GLIBC_') or ver.startswith('GCC_')):
            continue
        if nm in exported:
            unit += 1
            continue
        if bind == 2:   # weak
            continue
        problems.append('imports %s (%s), which no listed unit library exports' % (nm, ver or 'unversioned'))
    for p in problems:
        print('FAIL  ' + p)
    if problems:
        return 1
    print('OK    %s: interpreter %s; NEEDED %s; newest %s; %d imports from the unit\'s libraries, all exported' %
          (binary, cur, ', '.join(needed), newest, unit))
    return 0


def main(argv):
    if len(argv) == 3 and argv[1] == 'stub-source':
        stub_source(argv[2]); return 0
    if len(argv) == 4 and argv[1] == 'set-interp':
        return set_interp(argv[2], argv[3])
    if len(argv) >= 3 and argv[1] == 'check':
        return check(argv[2:])
    print(__doc__)
    return 2


if __name__ == '__main__':
    sys.exit(main(sys.argv))
