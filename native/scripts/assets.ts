// Растры для нативного приложения из ТЕХ ЖЕ PNG, что и в браузере (src/assets).
// Только уменьшение и заливка известным фоном; проверка размеров/формата исходников.

import { createHash } from 'node:crypto';
import { readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { decodePng, encodeEmbedded, flatten, hexRgb, resizeArea, type EmbeddedImage } from '../src/assets/codec';
import { ASSETS, type AssetKey, type AssetSpec } from '../src/assets/spec';
import { ROOT } from './bundle';

export const ASSET_DIR = join(ROOT, 'src', 'assets');
/** Меняется при изменении формата/алгоритма — инвалидирует кэш сборки. */
const PIPELINE = 'xop-assets/1;area-resize;filter-minsum;deflate9';

/** Отпечаток входов: спецификация + размер/время изменения исходников. */
export function assetsFingerprint(specs: readonly AssetSpec[] = ASSETS): string {
  const h = createHash('sha256').update(PIPELINE).update(JSON.stringify(specs));
  for (const s of specs) {
    const st = statSync(join(ASSET_DIR, s.file));
    h.update(`${s.file}:${st.size}:${Math.floor(st.mtimeMs)}`);
  }
  return h.digest('hex').slice(0, 16);
}

export function buildImage(spec: AssetSpec, png: Uint8Array = readFileSync(join(ASSET_DIR, spec.file))): EmbeddedImage {
  const src = decodePng(png);
  if (src.w !== spec.srcW || src.h !== spec.srcH) {
    throw new Error(`${spec.file}: expected ${spec.srcW}x${spec.srcH}, got ${src.w}x${src.h} (asset replaced? update native/src/assets/spec.ts)`);
  }
  const small = resizeArea(src, spec.w, spec.h);
  return spec.flattenOn ? encodeEmbedded(flatten(small, hexRgb(spec.flattenOn)), 3) : encodeEmbedded(small, 4);
}

export function buildAssetsModule(log: (s: string) => void = () => undefined): { code: string; fingerprint: string } {
  const fingerprint = assetsFingerprint();
  const decodedByFile = new Map<string, ReturnType<typeof decodePng>>();
  const images: Partial<Record<AssetKey, EmbeddedImage>> = {};
  for (const spec of ASSETS) {
    // Один исходник может давать несколько размеров (схема сверху): декодируем один раз.
    let src = decodedByFile.get(spec.file);
    if (!src) {
      src = decodePng(readFileSync(join(ASSET_DIR, spec.file)));
      decodedByFile.set(spec.file, src);
    }
    if (src.w !== spec.srcW || src.h !== spec.srcH) throw new Error(`${spec.file}: expected ${spec.srcW}x${spec.srcH}, got ${src.w}x${src.h}`);
    const small = resizeArea(src, spec.w, spec.h);
    const e = spec.flattenOn ? encodeEmbedded(flatten(small, hexRgb(spec.flattenOn)), 3) : encodeEmbedded(small, 4);
    images[spec.key] = e;
    log(`  ${spec.key.padEnd(13)} ${spec.file} ${spec.srcW}x${spec.srcH} -> ${e.w}x${e.h} ${e.ch === 3 ? 'RGB' : 'RGBA'} ${(e.z.length / 1024).toFixed(0)} KB`);
  }
  const code =
    "'use strict';\n" +
    `// xDrive Offroad Pro raster assets, generated by native/scripts/build.ts from src/assets/*.png (fingerprint ${fingerprint}).\n` +
    '// Downscaled + flattened copies of the project images; format: native/src/assets/codec.ts. Do not edit.\n' +
    `module.exports = ${JSON.stringify({ format: 'xop-assets/1', fingerprint, images })};\n`;
  return { code, fingerprint };
}
