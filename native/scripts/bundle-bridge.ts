// npm run native:bundle-bridge
//
// bridge.js для набора xop-camera-bridge: один CommonJS-файл для Node 8.7+ (на блоке /usr/bin/node — 8.16.2 / 8.9.4)
// из native/bridge/src/main.ts. Запускается бинарник esbuild из node_modules (тот же пакет, что у Vite) без его JS API:
// при выгруженных iCloud-файлах node_modules/esbuild/lib/main.js может читаться пустым, а бинарник — обычный файл.
// Вход только из native/bridge/src и native/src/camera; наружу — только встроенные модули Node. Выход:
// native/build/xop-camera-bridge/bridge.js (+ meta.json). Синтаксис на настоящем Node 8 проверяет
// release_tools.py (verify-kit / assemble, --node8).

import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, renameSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
export const BRIDGE_ENTRY = join(ROOT, 'native', 'bridge', 'src', 'main.ts');
export const BRIDGE_OUT_DIR = join(ROOT, 'native', 'build', 'xop-camera-bridge');
export const BRIDGE_JS = join(BRIDGE_OUT_DIR, 'bridge.js');
export const NODE_TARGET = 'node8.7';
/** Входы бандла: только код моста и общий протокол камер приложения. */
const ALLOWED_INPUT = /^native\/(bridge\/src\/[A-Za-z0-9_]+\.ts|src\/camera\/[A-Za-z0-9_]+\.ts)$/;
const NODE_BUILTINS = ['child_process', 'fs', 'net', 'path', 'os', 'crypto', 'events', 'util', 'buffer', 'stream', 'string_decoder', 'readline', 'timers'];

function fail(msg: string): never {
  throw new Error(`bundle-bridge: ${msg}`);
}

/** Бинарник esbuild для этой машины (пакет @esbuild/<платформа>-<архитектура> или esbuild/bin). */
export function esbuildBinary(root = ROOT): string {
  const candidates = [join(root, 'node_modules', '@esbuild', `${process.platform}-${process.arch}`, 'bin', 'esbuild'), join(root, 'node_modules', 'esbuild', 'bin', 'esbuild')];
  for (const c of candidates) {
    if (existsSync(c) && statSync(c).size > 1 << 20) return c;
  }
  return fail(`no esbuild binary in node_modules (looked at ${candidates.map((c) => relative(root, c)).join(', ')}); run npm ci`);
}

export interface BridgeBundle {
  readonly file: string;
  readonly bytes: number;
  readonly inputs: readonly string[];
  readonly requires: readonly string[];
}

export function bundleBridge(outDir = BRIDGE_OUT_DIR, root = ROOT): BridgeBundle {
  if (!existsSync(BRIDGE_ENTRY)) fail(`${relative(root, BRIDGE_ENTRY)} is missing`);
  const bin = esbuildBinary(root);
  mkdirSync(outDir, { recursive: true });
  const tmp = join(outDir, `.bridge-${process.pid}.js`);
  const meta = join(outDir, 'meta.json');
  const args = [
    relative(root, BRIDGE_ENTRY),
    '--bundle',
    '--platform=node',
    '--format=cjs',
    `--target=${NODE_TARGET}`,
    '--tsconfig=native/tsconfig.json',
    '--charset=utf8',
    '--legal-comments=inline',
    '--log-level=warning',
    `--banner:js='use strict';\n// xop-camera-bridge: generated by native/scripts/bundle-bridge.ts from native/bridge/src. Do not edit.`,
    `--metafile=${meta}`,
    `--outfile=${tmp}`,
  ];
  const r = spawnSync(bin, args, { cwd: root, encoding: 'utf8' });
  if (r.error) fail(`${bin}: ${r.error.message}`);
  if (r.status !== 0) {
    rmSync(tmp, { force: true });
    fail(`esbuild failed (exit ${r.status}):\n${(r.stderr || r.stdout).trim()}`);
  }
  const inputs = Object.keys((JSON.parse(readFileSync(meta, 'utf8')) as { inputs: Record<string, unknown> }).inputs).sort();
  const foreign = inputs.filter((i) => !ALLOWED_INPUT.test(i));
  if (foreign.length) {
    rmSync(tmp, { force: true });
    fail(`the bridge bundle may only take native/bridge/src and native/src/camera; it also took ${foreign.join(', ')}`);
  }
  const text = readFileSync(tmp, 'utf8');
  const requires = Array.from(new Set(Array.from(text.matchAll(/\brequire\(\s*["']([^"']+)["']\s*\)/g), (m) => m[1]))).sort();
  const bad = requires.filter((q) => !NODE_BUILTINS.includes(q));
  if (bad.length) {
    rmSync(tmp, { force: true });
    fail(`bridge.js requires ${bad.join(', ')}; only Node built-ins exist on the head unit`);
  }
  if (/\/Users\/|\/private\/|\/home\//.test(text)) {
    rmSync(tmp, { force: true });
    fail('bridge.js contains a build-machine path');
  }
  renameSync(tmp, join(outDir, 'bridge.js'));
  writeFileSync(join(outDir, 'inputs.txt'), `${inputs.join('\n')}\n`);
  return { file: join(outDir, 'bridge.js'), bytes: Buffer.byteLength(text), inputs, requires };
}

const isMain = process.argv[1] && /native[\\/]scripts[\\/]bundle-bridge\.ts$/.test(process.argv[1]);
if (isMain) {
  try {
    const b = bundleBridge();
    console.log(`${relative(ROOT, b.file)}: ${b.bytes} bytes, target ${NODE_TARGET}, requires ${b.requires.join(', ')}`);
    console.log(`inputs: ${b.inputs.join(', ')}`);
  } catch (e) {
    console.error(String((e as Error).message ?? e));
    process.exit(1);
  }
}
