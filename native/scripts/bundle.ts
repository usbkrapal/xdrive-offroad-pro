// Сборка main.js из native/src (и общего src/domain, src/providers/mock, src/components/motion …)
// через API esbuild, который уже установлен как зависимость Vite (package-lock: esbuild 0.25.x).
// Выход: один CommonJS-файл для Node 8.7; рантайм upstream ('./kit/*') и './assets' — внешние.

import { build, type Plugin } from 'esbuild';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
export const NATIVE = join(ROOT, 'native');
export const NODE_TARGET = 'node8.7';

/** './kit/…' и './assets' остаются require() во время выполнения (их кладёт build.py / наша сборка). */
const runtimeExternals: Plugin = {
  name: 'xop-runtime-externals',
  setup(b) {
    b.onResolve({ filter: /^\.\/(kit\/[a-z_]+|assets)$/ }, (args) => ({ path: args.path, external: true }));
    // Браузерные модули не должны попасть в нативный бандл.
    b.onResolve({ filter: /^(react|react-dom)(\/.*)?$/ }, (args) => ({ errors: [{ text: `${args.path} must not be imported by the native app (from ${args.importer})` }] }));
    b.onResolve({ filter: /\.(png|jpe?g|css|svg)$/ }, (args) => ({ errors: [{ text: `asset import ${args.path} must go through native/scripts/assets.ts (from ${args.importer})` }] }));
  },
};

export async function bundleMain(): Promise<string> {
  const res = await build({
    absWorkingDir: ROOT,
    entryPoints: [join(NATIVE, 'src', 'main.ts')],
    bundle: true,
    write: false,
    platform: 'node',
    format: 'cjs',
    target: NODE_TARGET,
    tsconfig: join(NATIVE, 'tsconfig.json'),
    charset: 'utf8',
    legalComments: 'inline',
    minify: false,
    sourcemap: false,
    logLevel: 'silent',
    banner: { js: "'use strict';\n// xDrive Offroad Pro — generated by native/scripts/build.ts from native/src. Do not edit." },
    plugins: [runtimeExternals],
  });
  if (res.errors.length) throw new Error(res.errors.map((e) => e.text).join('\n'));
  return res.outputFiles[0].text;
}
